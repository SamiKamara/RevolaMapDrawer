// Development only. Players use the bundled snapshot, never this checkout path.
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root = fileURLToPath(new URL('..', import.meta.url));
const source = path.resolve(process.argv[2] || path.join(root, '../Revola/Assets/RevolaMapManager/Runtime/Resources/RevolaMapDrawerPlacementDefaults.json'));
const defaults = JSON.parse(await fs.readFile(source, 'utf8'));
if (defaults.version !== 1 || !defaults.density?.npc || !defaults.prefabs?.length || !defaults.rangedWeapons?.length) throw new Error('Export current Map Manager placement defaults first.');
await fs.writeFile(path.join(root, 'src/placement-defaults.js'), '// Generated by MapDrawerPlacementDefaultsExport; refresh with scripts/sync-placement-defaults.mjs.\nexport const PLACEMENT_DEFAULTS = ' + JSON.stringify(defaults, null, 2) + ';\n');
console.log(`Synchronized ${defaults.prefabs.length} audited default prefabs.`);
