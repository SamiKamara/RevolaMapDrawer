"""Trace current Unity monochrome sprites into maintained SVG and Canvas paths.

Requires Python, Pillow, numpy and opencv-python-headless. First run Unity's
Revola.MapManager.MapDrawerVisualExport.Export in the sibling game checkout.
Usage: python scripts/trace-object-sprites.py <Revola checkout> [source.json]
No colored sprite, embedded raster, or network resource is accepted.
"""
import hashlib
import json
import sys
from pathlib import Path

import cv2
import numpy as np
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
GAME = Path(sys.argv[1]).resolve()
source = Path(sys.argv[2]).resolve() if len(sys.argv) > 2 else GAME / 'Library/RevolaMapManager/DrawerVisuals/source.json'
manifest = json.loads(source.read_text(encoding='utf-8-sig'))
output = ROOT / 'assets/object-vectors'
output.mkdir(exist_ok=True)
vectors, provenance = {}, {}


def trace(mask):
    contours, _ = cv2.findContours(mask.astype(np.uint8), cv2.RETR_LIST, cv2.CHAIN_APPROX_SIMPLE)
    paths = []
    for contour in contours:
        if abs(cv2.contourArea(contour)) < 1:
            continue
        points = cv2.approxPolyDP(contour, .45, True).reshape(-1, 2)
        paths.append('M' + 'L'.join(f'{x},{y}' for x, y in points) + 'Z')
    return ''.join(paths)


for key, visual in manifest['visuals'].items():
    # Pixel coordinate +X is prefab forward (+Z); +Y is prefab right (+X).
    layers = sorted(visual['layers'], key=lambda layer: (layer['order'], layer['corners'][0][1]))
    extent = max(abs(p[axis]) for layer in layers for p in layer['corners'] for axis in (0, 2)) * 2
    extent *= 1.05
    resolution = 384
    image = Image.new('RGBA', (resolution, resolution))
    files = []
    for layer in layers:
        path = GAME / layer['texture']
        original = Image.open(path).convert('RGBA')
        x, y, width, height = map(round, layer['rect'])
        raster = original.crop((x, original.height-y-height, x+width, original.height-y))
        rgb = np.asarray(raster)
        opaque = rgb[:, :, 3] > 32
        if np.any((rgb[:, :, :3].max(axis=2).astype(int) - rgb[:, :, :3].min(axis=2).astype(int))[opaque] > 8):
            raise ValueError(f'Colored legacy sprite is forbidden: {path}')
        projected = np.array(layer['corners'])[:, [2, 0]]
        # Door placement rotation is its opening tangent, not an NPC's facing.
        # The canonical sliding leaf spans local X, so align that span to +X.
        if key in ('door', 'door-hinged'):
            projected = projected[:, [1, 0]] * [1, -1]
        a, b, c = projected
        # Source PNG starts at its top left; Unity rect coordinates at bottom left.
        forward = np.column_stack(((b-a)/width, (a-c)/height)) * resolution/extent
        inverse = np.linalg.inv(forward)
        origin = c * resolution/extent + resolution/2
        translation = -inverse @ origin
        coefficients = (*inverse[0], translation[0], *inverse[1], translation[1])
        image.alpha_composite(raster.transform((resolution, resolution), Image.Transform.AFFINE, coefficients, Image.Resampling.BICUBIC))
        files.append({'texture': layer['texture'], 'sha256': hashlib.sha256(path.read_bytes()).hexdigest(), 'sprite': layer['sprite']})
    if key == 'door-hinged':
        # A hinge prefab's origin is at the jamb. Its editor marker represents
        # the opening center; center the closed leaf and align its span to +X.
        bounds = image.getbbox()
        leaf = image.crop(bounds)
        if leaf.height > leaf.width:
            leaf = leaf.transpose(Image.Transpose.ROTATE_90)
        image = Image.new('RGBA', (resolution, resolution))
        image.alpha_composite(leaf, ((resolution-leaf.width)//2, (resolution-leaf.height)//2))
    pixels = np.asarray(image)
    opaque = pixels[:, :, 3] >= 96
    white = opaque & (pixels[:, :, :3].mean(axis=2) >= 128)
    paths = [{'fill': '#000', 'd': trace(opaque)}, {'fill': '#fff', 'd': trace(white)}]
    svg = f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {resolution} {resolution}">' + ''.join(f'<path fill="{p["fill"]}" fill-rule="evenodd" d="{p["d"]}"/>' for p in paths) + '</svg>\n'
    (output / f'{key}.svg').write_text(svg, encoding='utf-8', newline='\n')
    ys, xs = np.nonzero(opaque)
    ink_fraction = max(int(xs.max()-xs.min()+1), int(ys.max()-ys.min()+1)) / resolution
    vectors[key] = {'extent': round(extent * 1000, 3), 'inkFraction': round(ink_fraction, 6), 'resolution': resolution, 'paths': paths}
    provenance[key] = {'prefab': visual['prefab'], 'sources': files, 'svgSha256': hashlib.sha256(svg.encode()).hexdigest()}

(ROOT / 'src/object-vectors.js').write_text('// Generated by scripts/trace-object-sprites.py. Game artwork: see docs/DISTRIBUTION.md.\nexport const OBJECT_VECTORS = ' + json.dumps(vectors, separators=(',', ':')) + ';\n', encoding='utf-8')
(ROOT / 'src/npc-defaults.js').write_text('// RevolaGladiatorGob prefab values, exported by MapDrawerVisualExport.\nexport const NPC_DEFAULTS = ' + json.dumps(manifest['npcDefaults'], indent=2) + ';\n', encoding='utf-8')
catalog = manifest['weaponCatalog']
if len({weapon['key'] for weapon in catalog}) != len(catalog) or not all(weapon['key'] in vectors for weapon in catalog):
    raise ValueError('Shop weapons need unique keys and monochrome vector previews.')
(ROOT / 'src/weapon-catalog.js').write_text('// Generated from both canonical shops, managed sale flags and English shop localization.\n// Refresh with MapDrawerVisualExport.Export and scripts/trace-object-sprites.py.\nexport const WEAPON_CATALOG = ' + json.dumps(catalog, indent=2) + ';\n', encoding='utf-8')
(output / 'provenance.json').write_text(json.dumps({'gameRepository': 'https://github.com/SamiKamara/Revola', 'method': '384px alpha + luminance contours; evenodd paths; 0.45px simplification; no raster embedding; SVG hashes use canonical LF text', 'weaponCatalog': catalog, 'catalogSources': manifest['catalogSources'], 'visuals': provenance}, indent=2) + '\n', encoding='utf-8')
print(f'Traced {len(vectors)} monochrome visuals; synchronized {len(catalog)} shop weapons and prefab defaults.')
